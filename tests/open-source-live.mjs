import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';

await mkdir('artifacts',{recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[],googleRequests=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(/maps\.googleapis\.com|routes\.googleapis\.com/.test(r.url()))googleRequests.push(r.url().split('?')[0])});
try {
  await page.goto('http://localhost:5173',{waitUntil:'domcontentloaded'});
  await page.getByRole('combobox',{name:'PICKUP LOCATION'}).fill('Rohini');
  await page.getByRole('combobox',{name:'DROP LOCATION'}).fill('Saket');
  await page.getByRole('combobox',{name:'Delivery window'}).selectOption('20');
  const responsePromise=page.waitForResponse(r=>r.url().endsWith('/api/calculate-route')&&r.request().method()==='POST',{timeout:90000});
  await page.getByRole('button',{name:'Show my ride',exact:true}).click();
  const response=await responsePromise;
  const result=await response.json();
  assert.equal(response.status(),200,JSON.stringify(result));
  assert.equal(result.routing_source,'OSRM / OpenStreetMap');
  assert.equal(result.geocoding_source,'Photon / OpenStreetMap');
  assert.equal(result.ranking_engine,'Neo4j Cypher');
  assert.equal(result.routes.length,4);
  assert.equal(result.aqi_source,'WAQI / monitoring stations');
  assert.equal(result.recommended_route_id,null);
  assert.equal(result.deadline_summary.any_route_on_time,false);
  await page.locator('.deadline-alert').waitFor();
  assert.match(await page.locator('.deadline-alert').innerText(),/20-minute deadline cannot be met/);
  assert.equal(await page.locator('.route-late').count(),4);
  assert.equal(await page.locator('.pollution-row').count(),4);
  assert.match(await page.locator('.data-note').innerText(),/World Air Quality Index/);
  assert.match(result.origin.formatted_address,/Rohini/);
  await page.locator('.live-endpoint').first().waitFor({timeout:90000});
  assert.equal(await page.locator('.live-endpoint').count(),2);
  assert.equal(await page.locator('.live-aqi-marker').count(),10);
  assert.equal(await page.locator('.map-service-error,.map-error').count(),0);
  await page.getByRole('button',{name:'Fit routes on map'}).click();
  await page.locator('.live-aqi-marker').first().click();
  await page.locator('.live-info-window').waitFor();
  assert.match(await page.locator('.live-info-window').innerText(),/Nearby station proxy/);
  await page.getByRole('button',{name:'Close popup'}).click();
  await page.screenshot({path:'artifacts/open-source-live-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'AQI samples'}).click();
  assert.equal(await page.locator('.live-aqi-marker').count(),0);
  await page.getByRole('button',{name:'AQI samples'}).click();
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right<=0.5);
  await page.getByRole('button',{name:'Fit routes on map'}).click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'artifacts/open-source-live-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  assert.deepEqual(googleRequests,[]);
  console.log(JSON.stringify({status:'PASS',services:'Photon + OSRM + WAQI stations + Neo4j + MapLibre/OpenFreeMap',routes:result.routes.length,graph:result.graph,minutes:result.routes.map(r=>Math.round(r.duration_seconds/60)),googleRequests:0}));
} finally {await browser.close()}
